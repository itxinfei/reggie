def main():
    # 读取data-test.sql中的图片路径
    sql_file = "src/test/resources/data-test.sql"
    base_dir = "uploads"

    print("正在扫描数据库中的图片路径...")

    # 存储所有图片路径
    image_paths = set()

    with open(sql_file, 'r', encoding='utf-8') as f:
        for line in f:
            # 匹配 images/dishes/ 或 images/setmeal/ 或 images/drinks/ 等路径
            if 'images/' in line and ('.jpg' in line or '.png' in line or '.jpeg' in line):
                # 提取图片路径（在单引号中）
                import re
                matches = re.findall(r"'(images/[^']+\.(jpg|jpeg|png))'", line, re.IGNORECASE)
                for match in matches:
                    image_paths.add(match[0])

    print(f"找到 {len(image_paths)} 个图片路径")

    # 创建不存在的图片文件
    created_count = 0
    skipped_count = 0

    for image_path in sorted(image_paths):
        full_path = os.path.join(base_dir, image_path)

        # 如果文件已存在，跳过
        if os.path.exists(full_path):
            print(f"  [跳过] {image_path} (已存在)")
            skipped_count += 1
            continue

        # 创建目录
        dir_path = os.path.dirname(full_path)
        if not os.path.exists(dir_path):
            os.makedirs(dir_path, exist_ok=True)
            print(f"  [创建目录] {dir_path}")

        # 创建占位图片
        size = create_placeholder_jpeg(full_path)
        print(f"  [创建] {image_path} ({size} bytes)")
        created_count += 1

    print(f"\n完成！")
    print(f"  新创建: {created_count} 个文件")
    print(f"  已存在: {skipped_count} 个文件")
    print(f"  总计: {len(image_paths)} 个文件")

if __name__ == "__main__":
    main()
